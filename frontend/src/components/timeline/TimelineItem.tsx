/**
 * components/timeline/TimelineItem.tsx
 *
 * A single event on the vertical timeline rail.
 *
 * Visual tiers:
 *   normal    – quiet white card, slate node
 *   borderline – amber tint, amber node
 *   abnormal  – orange tint, border-l-4, slightly larger padding, "Needs attention" label
 *   critical  – red tint, border-l-4, motion-safe:animate-pulse node ring, bold title
 *
 * "View details" scrolls to + highlights the matching row/card via scrollAndHighlight().
 * Respects prefers-reduced-motion: pulse and scroll animations are disabled.
 */

import {
  AlertTriangle,
  CalendarCheck,
  FlaskConical,
  Pill,
  Stethoscope,
} from "lucide-react";
import type { TimelineEvent, SupportedLanguage } from "../../types/health";
import { SeverityBadge } from "../dashboard/SeverityBadge";
import { formatEventDate, scrollAndHighlight } from "../../lib/timeline";

// ---------------------------------------------------------------------------
// Severity-driven style maps
// ---------------------------------------------------------------------------

const NODE_CLASSES: Record<string, string> = {
  normal: "bg-slate-100 text-slate-500",
  borderline: "bg-amber-100 text-amber-700",
  abnormal: "bg-orange-100 text-orange-700",
  critical: "bg-red-600 text-white",
};

const CARD_CLASSES: Record<string, string> = {
  // Normal: full glass look — translucent white, blurred backdrop
  normal: "bg-white/70 backdrop-blur-md border-white/40 shadow-xl shadow-slate-200/50",
  // Borderline: amber tint + blur so it pops but matches the glass system
  borderline: "bg-amber-50/80 backdrop-blur-md border-amber-200 shadow-xl shadow-amber-100/50",
  // Abnormal: orange tint + left stripe + blur — visually dominant
  abnormal:
    "bg-orange-50/80 backdrop-blur-md border-orange-300 border-l-4 border-l-orange-500 shadow-xl shadow-orange-100/60",
  // Critical: red tint + left stripe + blur — most dominant
  critical: "bg-red-50/80 backdrop-blur-md border-red-300 border-l-4 border-l-red-600 shadow-xl shadow-red-100/60",
};

const CARD_PADDING: Record<string, string> = {
  normal: "p-4",
  borderline: "p-4",
  abnormal: "p-5",
  critical: "p-5",
};

// ---------------------------------------------------------------------------
// Category icon
// ---------------------------------------------------------------------------

function CategoryIcon({ category }: { category: TimelineEvent["category"] }) {
  const cls = "h-4 w-4 shrink-0";
  switch (category) {
    case "medication":
      return <Pill className={cls} aria-hidden="true" />;
    case "lab":
      return <FlaskConical className={cls} aria-hidden="true" />;
    case "diagnosis":
      return <Stethoscope className={cls} aria-hidden="true" />;
    default:
      return <CalendarCheck className={cls} aria-hidden="true" />;
  }
}

// ---------------------------------------------------------------------------
// TimelineItem
// ---------------------------------------------------------------------------

interface TimelineItemProps {
  event: TimelineEvent;
  language: SupportedLanguage;
}

export function TimelineItem({ event, language }: TimelineItemProps) {
  const sev = event.severity ?? "normal";
  const isFlagged = sev === "abnormal" || sev === "critical";
  const isBorderline = sev === "borderline";
  const isUrgent = sev === "critical";

  // Must match the id generated by LabResultsTable rows and MedicationCard divs
  const relatedId = event.related_ref
    ? `timeline-target-${event.related_ref.toLowerCase().replace(/\s+/g, "-")}`
    : null;

  function handleViewDetails() {
    if (relatedId) scrollAndHighlight(relatedId);
  }

  return (
    <li className="relative pl-10 pb-6 last:pb-2">
      {/* ── Rail node ───────────────────────────────────────────────────── */}
      {/*
        motion-safe:animate-pulse: pulses only when the OS has NOT opted into
        reduced motion, which satisfies the prefers-reduced-motion requirement.
      */}
      <div
        aria-hidden="true"
        className={[
          "absolute left-0 top-2 flex h-8 w-8 shrink-0 items-center justify-center",
          "rounded-full ring-4 ring-white",
          NODE_CLASSES[sev] ?? NODE_CLASSES.normal,
          isUrgent ? "motion-safe:animate-pulse" : "",
        ]
          .filter(Boolean)
          .join(" ")}
      >
        <CategoryIcon category={event.category} />
      </div>

      {/* ── Card ────────────────────────────────────────────────────────── */}
      <div
        className={[
          "rounded-xl border",
          CARD_CLASSES[sev] ?? CARD_CLASSES.normal,
          CARD_PADDING[sev] ?? "p-4",
          "space-y-2",
        ].join(" ")}
      >
        {/* "Needs attention" label for abnormal / critical / borderline items */}
        {(isFlagged || isBorderline) && (
          <div className="flex items-center gap-1.5">
            <AlertTriangle
              className={`h-3.5 w-3.5 shrink-0 ${
                isUrgent
                  ? "text-red-500"
                  : isFlagged
                  ? "text-orange-500"
                  : "text-amber-500"
              }`}
              aria-hidden="true"
            />
            <span
              className={`text-xs font-semibold uppercase tracking-wider ${
                isUrgent
                  ? "text-red-600"
                  : isFlagged
                  ? "text-orange-600"
                  : "text-amber-600"
              }`}
            >
              {isUrgent ? "Needs immediate attention" : "Needs attention"}
            </span>
          </div>
        )}

        {/* Date + badge row */}
        <div className="flex flex-wrap items-center gap-2">
          <time
            dateTime={event.date ?? undefined}
            className="text-xs text-slate-400 shrink-0"
          >
            {formatEventDate(event.date, language)}
          </time>
          <SeverityBadge severity={sev} size="sm" />
        </div>

        {/* Title */}
        <p
          className={[
            "text-sm leading-snug",
            isUrgent
              ? "font-semibold text-red-800"
              : isFlagged
              ? "font-semibold text-slate-800"
              : "font-medium text-slate-700",
          ].join(" ")}
        >
          {event.title}
        </p>

        {/* Description */}
        <p className="text-xs leading-relaxed text-slate-500 summary-text">
          {event.description}
        </p>

        {/* View details link — keyboard-focusable via button role */}
        {relatedId && (
          <button
            type="button"
            onClick={handleViewDetails}
            className="mt-1 text-xs font-medium text-teal-600 underline-offset-2 hover:underline focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-teal-500 rounded"
          >
            View details ↓
          </button>
        )}
      </div>
    </li>
  );
}
